"""Scan zones B/A in 30-degree steps, count unique pumpkins, and harvest.

Scan order:
    B: 0, -30, -60, -90, -120, -140 degrees
    return to 0
    A: 0, +30, +60, +90, +120, +140 degrees

The A/B pixel-to-robot homographies are converted to a common arm-local frame
and rotated with joint1. Detections closer than DUPLICATE_DISTANCE_M are merged,
so a pumpkin visible from adjacent views is counted once.

After scanning, every target is checked with non-moving inverse kinematics at
both approach and grasp heights. The old fixed 89.5-degree pitch is not used.
Actual harvesting begins only after the operator types HARVEST ALL.

Press Q in the video window or Ctrl-C to stop. Keep the mobile robot stationary
from the first camera frame until harvesting has finished.
"""

